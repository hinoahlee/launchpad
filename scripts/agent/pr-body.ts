// Prints a PR description with .github/pull_request_template.md's headings, prefilled from git and the run's state.
// The agent writes only What, Why and Read in this order (marked TODO); everything checkable comes from here.
// Usage: node scripts/agent/pr-body.ts > .workflow/pr.md
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync } from "node:fs";
import path from "node:path";
import { countTests, isMigration, isTestFile } from "../test-integrity.ts";
import { parseReview } from "./review.ts";
import { type CheckResult, readState, repoRoot, workflowDir } from "./state.ts";

const root = repoRoot;
const git = (args: string[]) =>
	execFileSync("git", args, {
		cwd: root,
		encoding: "utf8",
		maxBuffer: 64 * 1024 * 1024,
	});
const state = readState(root);
const base = git(["merge-base", "origin/main", "HEAD"]).trim();
const head = git(["rev-parse", "HEAD"]).trim();

const files = git(["diff", "--no-renames", "--name-status", `${base}..HEAD`])
	.split("\n")
	.filter(Boolean)
	.map((line) => {
		const [status = "", file = ""] = line.split("\t");
		return { status: status[0] ?? "M", file };
	});

const groups = {
	src: files.filter(
		(f) =>
			!isTestFile(f.file) &&
			!isMigration(f.file) &&
			/\.(ts|tsx|css)$/.test(f.file),
	),
	tests: files.filter((f) => isTestFile(f.file)),
	migrations: files.filter((f) => isMigration(f.file)),
};
const other = files.filter((f) => !Object.values(groups).flat().includes(f));
const list = (entries: typeof files) =>
	entries.length
		? entries.map((f) => `- \`${f.status}\` ${f.file}`).join("\n")
		: "- none";

const show = (ref: string, file: string) => {
	try {
		return git(["show", `${ref}:${file}`]);
	} catch {
		return "";
	}
};
const testDelta = groups.tests.map((f) => {
	const before = countTests(show(base, f.file));
	const after = countTests(show(head, f.file));
	const kind =
		f.status === "A" ? "added" : f.status === "D" ? "removed" : "modified";
	return `- ${f.file}: ${kind}, ${before} → ${after} tests`;
});

const check = (name: string, result?: CheckResult) =>
	!result
		? `${name}: not run`
		: `${name}: ${result.ok ? "passed" : "FAILED"} at ${result.sha.slice(0, 7)}${result.sha === head ? " (this commit)" : " (an older commit)"}`;

const slug = state.slug ?? "unknown";
const specPath = path.join(workflowDir(root), "specs", `${slug}.md`);
const spec = existsSync(specPath)
	? readFileSync(specPath, "utf8").trim()
	: "(no spec found)";

const reviews = state.reviews ?? [];
const last = [...reviews]
	.sort((a, b) => b.round - a.round)
	.find((r) => r.status === "ok");
const remaining =
	last?.file && existsSync(path.join(root, last.file))
		? parseReview(
				readFileSync(path.join(root, last.file), "utf8"),
			).findings.map((f) => `- ${f.kind} ${f.location} ${f.text}`)
		: [];

const trailers = git(["log", "--format=%B", `${base}..HEAD`])
	.split("\n")
	.filter((line) => line.startsWith("Tests-changed:"));

console.log(`## What

TODO(agent): one or two sentences.

## Why

TODO(agent): the problem from the spec, in the user's words.

## Read in this order
1. TODO(agent): path — what to look for (pick from the changed files below)

## Try it

Spec and acceptance criteria are below; each names the test that proves it. To reproduce the checks: \`pnpm verify\`${state.gate.lastE2e ? " and `pnpm e2e`" : ""}.

## Tests changed or removed (and why)

${trailers.length ? trailers.map((t) => `- ${t.replace("Tests-changed:", "").trim()}`).join("\n") : "- none"}

---
<details><summary>Run record (generated by scripts/agent/pr-body.ts)</summary>

**Checks**
- ${check("pnpm verify", state.gate.lastVerify)}
- ${state.gate.lastE2e ? check("pnpm e2e", state.gate.lastE2e) : "pnpm e2e: not run (no browser-facing change)"}
- Stop-gate failures during the run: ${state.gate.verifyFailures}

**Changed files**
Source:
${list(groups.src)}

Tests:
${list(groups.tests)}
${testDelta.join("\n")}

Migrations:
${list(groups.migrations)}

Other:
${list(other)}

**Reviewer** (${reviews.length ? reviews.map((r) => `round ${r.round}: ${r.status}, ${r.confirmed} confirmed / ${r.plausible} plausible / ${r.style} style`).join("; ") : "not run"})
${remaining.length ? `Findings from the last round, for a human to judge:\n${remaining.join("\n")}` : "No findings left from the last round."}

**Spec** (\`.workflow/specs/${slug}.md\`)

${spec}

</details>`);
